let currentLocale = (typeof localStorage !== 'undefined' && localStorage.getItem('agrispectra_lang')) || 'en';
const listeners = new Set();

export function getLocale() {
  return currentLocale;
}

export function setLocale(localeCode) {
  if (DICTIONARY[localeCode]) {
    currentLocale = localeCode;
    try {
      if (typeof localStorage !== 'undefined') {
        localStorage.setItem('agrispectra_lang', localeCode);
      }
    } catch (e) {}
    listeners.forEach(fn => fn(currentLocale));
  }
}

export function t(key, fallback = '') {
  const dict = DICTIONARY[currentLocale] || DICTIONARY.en;
  return dict[key] || DICTIONARY.en[key] || fallback || key;
}

export function onLocaleChange(callback) {
  listeners.add(callback);
  return () => listeners.delete(callback);
}
